// Family I: identity (test-baseline.md §Family I). TB-I1 ids in titles, TB-I2 ids unique across the suite
// and indexed (with --suite; the index is generated or checked by --id-index), TB-I3 title and tags match the
// scenario block (projects with specs.shape), TB-I4 per-test defect pointers.
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { globToRegExp } from '../config-scope.mjs';
import { isCall, isMember, propName, unwrap, anyNode, declarations, tagsOf, testModifier } from '../shapes.mjs';
