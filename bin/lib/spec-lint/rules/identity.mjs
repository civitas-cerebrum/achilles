const RULEBOOK = 'skills/achilles-orchestrator/references/test-baseline.md';

export const RULES = [
  { id: 'TB-I1', title: 'test without a stable id', severity: 'blocking', appliesTo: ['spec'], do: "Start the title with the test's id in the project's pattern, then ` · ` and the behaviour (`TCLG-000420 · a wrong password is rejected`)." },
  { id: 'TB-I2', title: 'id used twice in the suite, or missing from the id index', severity: 'blocking', appliesTo: ['spec'], do: 'Give the new case a fresh id and list it in the id index (`achilles-spec-lint --id-index` regenerates it).' },
  { id: 'TB-I3', title: 'title or tags differ from the scenario block', severity: 'blocking', appliesTo: ['spec'], do: "Title the test '<ID> · <the block's title>' and give it the block's Type tags (the `tag` option preferred)." },
  { id: 'TB-I4', title: 'expected-red test without a resolvable defect pointer', severity: 'blocking', appliesTo: ['spec'], do: 'Add `// defect: <path#anchor | KEY-n | TICKET-Dn>` to the comment block directly above the test (or its @known-defect describe), pointing at a record that exists.' },
];

/** The id index: ids listed in the file (any token the pattern matches anywhere on a line). */
export function readIndex(root, pattern) {
  const abs = path.join(root, INDEX_FILE);
  if (!existsSync(abs)) return null;
  const core = pattern.re.source.replace(/^\^\\s\*/, '').replace(/^\^/, '').replace(/\(\?=[^)]*\)$/, '');
  let re;
  try { re = new RegExp(core, 'g'); } catch { return null; }
  const ids = new Set();
  for (const m of readFileSync(abs, 'utf8').matchAll(re)) ids.add((m[1] || m[0]).trim());
  return ids;
}

/** The index text for the suite's tests (`--id-index`), with the retired ids kept below (never reused). */
export function renderIndex(entries, retired = []) {
  const rows = [...entries].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const esc = (s) => String(s).replace(/\|/g, '\\|');
  const behaviour = (r) => { const i = r.title.indexOf(r.id); return (i === -1 ? r.title : r.title.slice(i + r.id.length)).replace(/^[\])]?\s*[·—:|-]?\s*/, ''); };
  const out = ['# Test ids', '', 'Generated by `achilles-spec-lint --id-index`. Look here before minting a new id; never reuse a retired one.', '', '| Id | Test | File |', '|---|---|---|', ...rows.map((r) => `| ${r.id} | ${esc(behaviour(r))} | \`${r.file}\` |`), ''];
  const gone = [...new Set(retired)].sort();
  if (gone.length) out.push('## Retired', '', 'Ids no test uses any more. They stay retired: a new case takes a fresh id.', '', '| Id |', '|---|', ...gone.map((id) => `| ${id} |`), '');
  return out.join('\n');
}

/** The ids a generated index lists: { active, retired } (the first column of each table). */
export function indexIds(text) {
  const active = new Set(), retired = new Set();
  let into = active;
  for (const line of String(text).split(/\r?\n/)) {
    if (/^##\s+Retired\b/i.test(line)) { into = retired; continue; }
    const m = /^\|\s*([^|\s]+)\s*\|/.exec(line);
    if (m && m[1] !== 'Id' && !/^-+$/.test(m[1])) into.add(m[1]);
  }
  return { active, retired };
}

const SKIP_DIRS = new Set(['node_modules', '.git', 'playwright-report', 'test-results', '.achilles']);
const norm = (t) => String(t).toLowerCase().replace(/\s+/g, ' ').replace(/[.\s]+$/, '').trim();

/** Scenario blocks of the specs.shape documents: id → { title, tags, file, line }. Null without specs.shape. */
export function scenarioBlocks(root, rules) {
  const shape = rules?.rules?.['specs.shape'];
  if (!shape || !Array.isArray(shape.scenarioDocs) || !shape.titleIdPattern) return null;
  const globs = shape.scenarioDocs.map((g) => globToRegExp(String(g)));
  const core = String(shape.titleIdPattern).replace(/^\^/, '').replace(/\s*(?:—|·)\s*$/, '');
  let heading;
  try { heading = new RegExp(`^####\\s+(${core})\\s+—\\s+(.+?)\\s*$`); } catch { return null; }
  const out = new Map();
  const walk = (dir) => {
    let entries;
    try { entries = readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const e of entries) {
      const abs = path.join(dir, e.name);
      if (e.isDirectory()) { if (!SKIP_DIRS.has(e.name)) walk(abs); continue; }
      const rel = path.relative(root, abs).split(path.sep).join('/');
      if (!rel.endsWith('.md') || !globs.some((g) => g.test(rel))) continue;
      let cur = null;
      readFileSync(abs, 'utf8').split(/\r?\n/).forEach((line, i) => {
        const h = heading.exec(line);
        if (h) { cur = { id: h[1], title: h[h.length - 1], tags: [], file: rel, line: i + 1 }; if (!out.has(cur.id)) out.set(cur.id, cur); return; }
        if (/^#{1,4}\s/.test(line) || /^---\s*$/.test(line)) { cur = null; return; }
        const t = cur && /^-\s+\*\*Type\*\*\s*:\s*(.*)$/.exec(line);
        if (t) cur.tags = [...t[1].matchAll(/@[\w-]+/g)].map((m) => m[0]);
      });
    }
  };
  walk(root);
  return out;
}

/**
 * A test title as text: a literal, or a file-level `const` string a title names (`test(TITLE, …)`); other
 * non-literal titles stay dynamic.
 */
function titleText(file, t) {
  if (!t.title || !t.title.dynamic || !t.title.node || t.title.node.type !== 'Identifier') return t.title;
  for (const st of file.ast.program.body) {
    const d = st.type === 'ExportNamedDeclaration' ? st.declaration : st;
    if (!d || d.type !== 'VariableDeclaration' || d.kind !== 'const') continue;
    for (const x of d.declarations) {
      const v = x.id.type === 'Identifier' && x.id.name === t.title.node.name ? unwrap(x.init) : null;
      if (v && (v.type === 'StringLiteral' || (v.type === 'TemplateLiteral' && !v.expressions.length))) return { text: v.type === 'StringLiteral' ? v.value : v.quasis[0].value.cooked, dynamic: false };
    }
  }
  return t.title;
}

export function visitors(project) {
  const pattern = idPattern(project.root, project.rules, process.env, project.baselineIdPattern, project.inputs ? project.inputs.envPattern : undefined);
  const blocks = scenarioBlocks(project.root, project.rules);
  project.idPattern = pattern;
  const push = (file, rule, line, message, extra = {}) => project.findings.push({
    rule, severity: extra.severity || 'blocking', file: file.rel || file, line, column: 1, region: extra.region || 'test', message,
    do: extra.do || RULES.find((r) => r.id === rule).do, why: `${RULEBOOK}#${rule.toLowerCase()}`, test: extra.test || null, stmtLine: line, waived: false,
  });
  let sawTests = false;

  function idsOfFile(file) {
    const d = declarations(file);
    sawTests ||= d.tests.length > 0;
    const seen = new Map();
    for (const t of d.tests) {
      const tt = file.testsByNode.get(t.call);
      const test = tt ? { title: tt.title, id: tt.id, line: tt.line } : null;
      const title = titleText(file, t);
      if (!title) continue;
      if (title.dynamic) { push(file, 'TB-I1', t.line, `${title.node ? 'the title is not a literal' : 'template-literal title'}: its id cannot be read statically (advisory)`, { severity: 'advisory', test }); continue; }
      const m = idOf(title.text, pattern);
      if (!m) {
        push(file, 'TB-I1', t.line, `title "${title.text.slice(0, 60)}" does not start with an id matching ${!pattern.pinned ? 'the house default (unpinned, advisory)' : pattern.text === 'house-default' ? `the house default recorded in ${pattern.source.replace(/ idPattern$/, '')}` : `the pinned pattern (${pattern.source})`}`, { severity: pattern.pinned ? 'blocking' : 'advisory', test });
        continue;
      }
      if (!/^\s*·\s/.test(m.rest) && m.rest.trim()) push(file, 'TB-I1', t.line, `id ${m.id} is followed by "${m.rest.trim().slice(0, 1)}"; the canonical separator is \` · \` (advisory)`, { severity: 'advisory', test });
      if (seen.has(m.id)) push(file, 'TB-I1', t.line, `id ${m.id} is used twice in this file (first at line ${seen.get(m.id)})`, { test });
      else seen.set(m.id, t.line);
    }
  }

  /** TB-I4: every @known-defect test or describe and every test.fail sentinel carries its own resolvable pointer. */
  function pointers(file) {
    const d = declarations(file);
    const stmtLine = (call) => { const st = findStatement(file, call); return st ? st.loc.start.line : call.loc.start.line; };
    const check = (call) => {
      const ps = pointersAbove(file, stmtLine(call));
      if (!ps.length) return { ok: false, problem: 'no `// defect:` pointer in its own comment block' };
      const rs = ps.map((p) => ({ p, r: resolveRef(project.root, p.ref) }));
      const good = rs.find((x) => x.r.ok);
      return good ? { ok: true } : { ok: false, problem: rs.map((x) => x.r.problem).join('; ') };
    };
    const coveredDescribes = new Set();
    for (const x of d.describes) {
      if (!tagsOf(x.call).has('@known-defect')) continue;
      const r = check(x.call);
      if (r.ok) coveredDescribes.add(x);
      else push(file, 'TB-I4', x.line, `@known-defect describe: ${r.problem}`, { region: 'describe' });
    }
    for (const t of d.tests) {
      const known = tagsOf(t.call).has('@known-defect');
      const mods = testModifier(t.call, file.testNames) || [];
      const info = (o) => { o = unwrap(o); return (o.type === 'Identifier' && (/^(testInfo|info)$/.test(o.name) || (t.fn.params[1] && t.fn.params[1].name === o.name))) || (isCall(o) && (testModifier(o, file.testNames) || []).join('.') === 'info'); };
      const marks = (x) => (isCall(x) && ((testModifier(x, file.testNames) || []).join('.') === 'fail' || (isMember(unwrap(x.callee)) && propName(unwrap(x.callee)) === 'fail' && info(unwrap(x.callee).object))))
        || (x.type === 'AssignmentExpression' && isMember(x.left) && propName(x.left) === 'expectedStatus' && info(x.left.object));
      const sentinel = mods.includes('fail') || anyNode(t.fn.body, marks, { intoFunctions: false }) || SENTINEL_TITLE.test(t.title ? t.title.text : '');
      if (!known && !sentinel) continue;
      if (t.describes.some((y) => coveredDescribes.has(y))) continue;
      const r = check(t.call);
      if (r.ok) continue;
      const tt = file.testsByNode.get(t.call);
      push(file, 'TB-I4', t.line, `${known ? '@known-defect test' : 'test.fail sentinel'}: ${r.problem}`, { test: tt ? { title: tt.title, id: tt.id, line: tt.line } : null });
    }
  }

  /** TB-I3: under specs.shape, a test's id names a block whose title and Type tags the test carries. */
  function scenario(file) {
    const d = declarations(file);
    for (const t of d.tests) {
      const title = titleText(file, t);
      if (!title || title.dynamic) continue;
      const m = idOf(title.text, pattern);
      if (!m) continue;
      const tt = file.testsByNode.get(t.call);
      const test = tt ? { title: tt.title, id: tt.id, line: tt.line } : null;
      const b = blocks.get(m.id);
      if (!b) { push(file, 'TB-I3', t.line, `no scenario block ${m.id} in the specs.shape scenario documents`, { test }); continue; }
      const problems = [];
      const behaviour = m.rest.replace(/^\s*[·—:|-]?\s*/, '').replace(/(\s+@[\w-]+)+\s*$/, '');
      if (norm(behaviour) !== norm(b.title)) problems.push(`the title says "${behaviour}" where the block says "${b.title}"`);
      const tags = new Set([...tagsOf(t.call), ...t.describes.flatMap((x) => [...tagsOf(x.call)])]);
      const missing = b.tags.filter((x) => !tags.has(x));
      if (missing.length) problems.push(`the test lacks the block's Type tag${missing.length === 1 ? '' : 's'} ${missing.join(' ')}`);
      if (problems.length) push(file, 'TB-I3', t.line, `${m.id} differs from its scenario block (${b.file}:${b.line}): ${problems.join('; ')}`, { test });
    }
  }

  return {
    fileEnd(file) {
      if (file.kind !== 'spec') return;
      idsOfFile(file);
      if (blocks) scenario(file);
      pointers(file);
    },
    projectEnd(p) {
      for (const msg of pattern.problems) p.projectFindings.push({ rule: 'TB-I1', severity: 'advisory', message: `${msg}; the house default applies`, do: 'Fix the pattern so it compiles as a regular expression with the id in group 1.', why: `${RULEBOOK}#tb-i1` });
      if (!pattern.pinned && sawTests) p.projectFindings.push({ rule: 'TB-I1', severity: 'advisory', message: 'no test-id pattern is pinned: TB-I1 is advisory until the project pins CIVITAS_TEST_ID_PATTERN or specs.shape.titleIdPattern, or records `"idPattern": "house-default"` in tests/compliance-baseline.json', do: 'Pin the pattern the suite already uses (or record the house default) so missing ids block.', why: `${RULEBOOK}#tb-i1` });
      if (!p.suite) return;
      // TB-I2: ids across the whole suite, and the id index
      const all = [];
      for (const f of p.allFiles.filter((x) => x.kind === 'spec')) for (const t of declarations(f).tests) {
        const title = titleText(f, t);
        if (!title || title.dynamic) continue;
        const m = idOf(title.text, pattern);
        if (m) all.push({ id: m.id, file: f, line: t.line, title: title.text, call: t.call });
      }
      p.suiteIds = all.map((x) => ({ id: x.id, file: x.file.rel, line: x.line, title: x.title }));
      const byId = new Map();
      for (const x of all) { if (!byId.has(x.id)) byId.set(x.id, []); byId.get(x.id).push(x); }
      const index = readIndex(p.root, pattern);
      for (const x of all) {
        if (!x.file.selected) continue;
        const tt = x.file.testsByNode.get(x.call);
        const test = tt ? { title: tt.title, id: tt.id, line: tt.line } : null;
        const others = byId.get(x.id).filter((y) => y.file !== x.file);
        if (others.length) push(x.file, 'TB-I2', x.line, `id ${x.id} is also used by ${others.map((y) => `${y.file.rel}:${y.line}`).join(', ')}`, { test });
        if (index && !index.has(x.id)) push(x.file, 'TB-I2', x.line, `id ${x.id} is not in the id index ${INDEX_FILE}`, { test, do: 'Regenerate the index with `achilles-spec-lint --id-index` and commit it with the test.' });
      }
    },
  };
}

/** The statement that holds a call (searching from the program). */
function findStatement(file, call) {
  let found = null;
  const rec = (n, stmt) => {
    if (found || !n || typeof n.type !== 'string') return;
    const s = /Statement$|Declaration$/.test(n.type) && n.type !== 'BlockStatement' ? n : stmt;
    if (n === call) { found = s; return; }
    if (n.start > call.start || n.end < call.end) return;
    for (const k of Object.keys(n)) {
      if (k === 'loc' || k.endsWith('Comments')) continue;
      const v = n[k];
      if (Array.isArray(v)) { for (const x of v) if (x && typeof x.type === 'string') rec(x, s); } else if (v && typeof v.type === 'string') rec(v, s);
    }
  };
  rec(file.ast.program, null);
  return found;
}

