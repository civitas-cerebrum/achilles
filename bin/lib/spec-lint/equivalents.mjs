// The shipped equivalence table (equivalents.json) and the shipped surfaces (surfaces/<version>.json):
// loading, the derivation scripts/build-equivalents.mjs runs, and the offline well-formedness check
// scripts/check-pack.mjs runs.
import { readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as semver from './semver.mjs';
import { shippedVersions, readSnapshot, SURFACES_DIR, PACKAGE } from './surface.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const EQUIVALENTS_FILE = path.join(HERE, 'equivalents.json');

let cache = null;
export function loadEquivalents(file = EQUIVALENTS_FILE) {
  if (!cache || file !== EQUIVALENTS_FILE) {
    const t = JSON.parse(readFileSync(file, 'utf8'));
    if (file !== EQUIVALENTS_FILE) return t;
    cache = t;
  }
  return cache;
}

/** First version (ascending) whose surface has `method`, or null. */
function since(method, ordered) {
  for (const { version, methods } of ordered) if (methods.has(method)) return version;
  return null;
}

/**
 * Joins the hand-curated source with the published surfaces. `surfaces` is [{ version, methods: string[] }].
 * Throws when a target exists in no published release (a typo in the source, or a renamed method).
 */
export function deriveEquivalents(source, surfaces) {
  const ordered = semver.sort(surfaces.map((s) => s.version)).map((v) => {
    const s = surfaces.find((x) => x.version === v);
    return { version: v, methods: new Set(s.methods) };
  });
  const missing = [];
  const withSince = (targets) => targets.map((m) => {
    const v = since(m, ordered);
    if (!v) missing.push(m);
    return { method: m, since: v };
  });
  const methods = {};
  for (const [raw, e] of Object.entries(source.methods)) methods[raw] = { ...e, targets: withSince(e.targets) };
  const http = {};
  for (const [raw, e] of Object.entries(source.http)) http[raw] = { ...e, targets: withSince(e.targets) };
  const evaluate = { methods: source.evaluate.methods, targets: withSince(source.evaluate.targets) };
  if (missing.length) throw new Error(`targets in no published release: ${[...new Set(missing)].join(', ')}`);
  return {
    $comment: 'Generated by scripts/build-equivalents.mjs from scripts/equivalents.source.json and the published releases; do not edit by hand.',
    package: source.package,
    releases: ordered.map((o) => o.version),
    methods, http, evaluate,
    noEquivalent: source.noEquivalent,
  };
}

/** Problems with the shipped tables (empty when well formed). Offline: reads only shipped files. */
export function checkShippedTables({ equivalentsFile = EQUIVALENTS_FILE, surfacesDir = SURFACES_DIR } = {}) {
  const problems = [];
  if (!existsSync(equivalentsFile)) return [`missing ${equivalentsFile}`];
  let eq;
  try { eq = JSON.parse(readFileSync(equivalentsFile, 'utf8')); } catch (e) { return [`equivalents.json is not JSON (${e.message})`]; }
  const versions = shippedVersions(surfacesDir);
  if (!versions.length) problems.push('no shipped surfaces');
  const surfaces = [];
  for (const v of versions) {
    let s;
    try { s = readSnapshot(v, surfacesDir); } catch (e) { problems.push(`surfaces/${v}.json is not JSON (${e.message})`); continue; }
    if (s.package !== PACKAGE) problems.push(`surfaces/${v}.json: package is ${JSON.stringify(s.package)}`);
    if (s.version !== v) problems.push(`surfaces/${v}.json: version is ${JSON.stringify(s.version)}`);
    if (!Array.isArray(s.methods) || !s.methods.length || s.methods.some((m) => typeof m !== 'string')) problems.push(`surfaces/${v}.json: methods must be a non-empty string list`);
    if (!s.privates || !Array.isArray(s.privates.steps)) problems.push(`surfaces/${v}.json: privates.steps missing`);
    surfaces.push({ version: v, methods: Array.isArray(s.methods) ? s.methods : [] });
  }
  if (JSON.stringify(eq.releases) !== JSON.stringify(versions)) problems.push('equivalents.json releases differ from the shipped surfaces');
  for (const k of ['methods', 'http']) if (!eq[k] || typeof eq[k] !== 'object') problems.push(`equivalents.json: ${k} missing`);
  if (!Array.isArray(eq.noEquivalent) || !eq.noEquivalent.length) problems.push('equivalents.json: noEquivalent table missing');
  else for (const e of eq.noEquivalent) {
    if (!Array.isArray(e.on) || !Array.isArray(e.methods) || !('row' in e)) problems.push(`equivalents.json: malformed noEquivalent entry ${JSON.stringify(e)}`);
    else if (e.row !== null && !/^FG-\d+$/.test(e.row)) problems.push(`equivalents.json: bad register row ${JSON.stringify(e.row)}`);
  }
  if (!problems.length) {
    // The table must be what the surfaces say: recompute every `since`.
    const strip = (o) => Object.fromEntries(Object.entries(o).map(([k, e]) => [k, { ...e, targets: e.targets.map((t) => t.method) }]));
    try {
      const again = deriveEquivalents({ package: eq.package, methods: strip(eq.methods), http: strip(eq.http), evaluate: { methods: eq.evaluate.methods, targets: eq.evaluate.targets.map((t) => t.method) }, noEquivalent: eq.noEquivalent }, surfaces);
      for (const k of ['methods', 'http', 'evaluate']) if (JSON.stringify(again[k]) !== JSON.stringify(eq[k])) problems.push(`equivalents.json: ${k} disagrees with the shipped surfaces (re-run npm run build:equivalents)`);
    } catch (e) { problems.push(`equivalents.json: ${e.message}`); }
  }
  return problems;
}
