#!/usr/bin/env node
// show.mjs — "show me" runner: run a Playwright suite in a visible, slowed-down
// browser and hand back a watchable video.
//
// Consumers reach this through the `achilles-show` bin:
//
//   npx achilles-show tests/regression/checkout.spec.ts
//   npx achilles-show --grep "TC_042"
//   E2E_VIEWPORTS=mobile npx achilles-show tests/regression_mobile
//
// Every argument is forwarded to `playwright test`, so the usual filters work.
//
// WHY THIS EXISTS. A green checkmark does not show what the test did. For QA
// review, sign-off, and handing evidence to a developer or stakeholder, the
// footage is the deliverable. See skills/ticket-driven-testing/SKILL.md §"Show
// me" for the methodology this implements.
//
// WHY IT GENERATES A CONFIG INSTEAD OF SHIPPING ONE. A demo run needs
// project-specific things this package cannot know: testDir, fixtures, viewport
// projects, baseURL, auth headers, webServer. So rather than asking every
// consumer to hand-write and maintain a second config, this derives one from
// the config the project already has and overrides only the handful of fields
// that make a run watchable. Nothing about the project's own config changes.
//
// The overrides, and why each is not optional:
//   headless: false     a real window — the point of the exercise
//   slowMo >= 1500ms    recordings are paced AT THE SOURCE so the native
//                       footage is watchable with no post-processing. 500ms
//                       proved too fast to track individual actions.
//   video/trace: on     always, not just on failure
//   workers: 1          parallel workers open several windows at once and
//                       produce interleaved footage nobody can follow
//   retries: 0          a retry overwrites the recording you just watched
//   long timeouts       slowMo multiplies every action's wall time, so
//                       CI-tuned timeouts fire spuriously
//
// Environment:
//   E2E_SLOWMO=<ms>          pause before each action (default 1500)
//   ACHILLES_SHOW_CONFIG     path to the base Playwright config to derive from
//                            (default: the first playwright.config.* found)
//   plus whatever the project's own config reads (baseURL, viewport selection…)

import { execFileSync, spawnSync } from 'node:child_process'
import * as fs from 'node:fs'
import { createRequire } from 'node:module'
import * as path from 'node:path'

const projectRoot = process.cwd()
const workDir = path.join(projectRoot, '.achilles', 'show')
const stamp = new Date().toISOString().replace(/[:.]/g, '-').replace('T', '_').slice(0, 19)
const destDir = path.join(projectRoot, 'show-recordings', stamp)

const SLOW_MO = Number(process.env.E2E_SLOWMO) || 1500
const args = process.argv.slice(2)

/** Find the project's own Playwright config — the one we derive from. */
function findBaseConfig() {
  if (process.env.ACHILLES_SHOW_CONFIG) {
    const explicit = path.resolve(projectRoot, process.env.ACHILLES_SHOW_CONFIG)
    if (!fs.existsSync(explicit)) {
      console.error(`✖ ACHILLES_SHOW_CONFIG points at a file that does not exist: ${explicit}`)
      process.exit(1)
    }
    return explicit
  }
  for (const name of ['playwright.config.ts', 'playwright.config.js', 'playwright.config.mts', 'playwright.config.mjs']) {
    const candidate = path.join(projectRoot, name)
    if (fs.existsSync(candidate)) return candidate
  }
  console.error('✖ No playwright.config.* found in', projectRoot)
  console.error('  Run achilles-show from your Playwright project root, or set ACHILLES_SHOW_CONFIG.')
  process.exit(1)
}

/**
 * Write the derived config in the SAME DIRECTORY as the base config.
 *
 * Playwright resolves `testDir`, `globalSetup`, `globalTeardown` and friends relative to the
 * config file's own directory — so a generated config in a subfolder silently breaks every one of
 * them ("Cannot find module './global-setup.ts'"). Sitting beside the original is what makes the
 * derived run behave identically to a normal one. The file is removed when the run finishes.
 *
 * `.ts`, not `.mts`: Playwright's loader resolves module format from the project's package.json,
 * and a bare `.mts` gets loaded as CJS ("Cannot use import statement outside a module").
 *
 * Overrides are applied to `projects[].use` as well as the top-level `use`: per-project `use` wins
 * over global `use`, so a project setting its own launchOptions would otherwise drop slowMo.
 */
function writeDerivedConfig(baseConfigPath) {
  fs.mkdirSync(workDir, { recursive: true })
  const generated = path.join(path.dirname(baseConfigPath), '.playwright-show.generated.ts')
  const rel = './' + path.basename(baseConfigPath)

  fs.writeFileSync(
    generated,
    `// GENERATED by achilles-show. Do not edit — removed when the run finishes.
// Derives a watchable, recorded run from ${path.basename(baseConfigPath)}.
import { defineConfig } from '@playwright/test'
import base from '${rel}'

const SLOW_MO = ${SLOW_MO}
const DEMO_TIMEOUT = 900_000

const withDemoUse = (use: any = {}) => ({
  ...use,
  headless: false,
  launchOptions: { ...(use.launchOptions ?? {}), slowMo: SLOW_MO },
  video: 'on' as const,
  trace: 'on' as const,
  navigationTimeout: Math.max(use.navigationTimeout ?? 0, 120_000),
  actionTimeout: Math.max(use.actionTimeout ?? 0, 60_000),
})

const cfg: any = base

export default defineConfig({
  ...cfg,
  fullyParallel: false,
  workers: 1,
  retries: 0,
  forbidOnly: false,
  timeout: Math.max(cfg.timeout ?? 0, DEMO_TIMEOUT),
  outputDir: ${JSON.stringify(path.join(workDir, 'output'))},
  reporter: [['list'], ['html', { open: 'never', outputFolder: ${JSON.stringify(path.join(workDir, 'report'))} }]],
  use: withDemoUse(cfg.use),
  projects: (cfg.projects ?? []).map((p: any) => ({ ...p, use: withDemoUse(p.use) })),
})
`,
    'utf8',
  )
  return generated
}

/**
 * Locate an ffmpeg that can actually produce mp4.
 *
 * Playwright records webm and ships a DECODE-ONLY ffmpeg — no mp4 muxer, no
 * h264 — so it cannot be used for this. `ffmpeg-static` is an optional
 * dependency; its binary arrives via a postinstall that package managers block
 * by default, so fetch it here on first use rather than demanding a workspace
 * build approval. Falls back to ffmpeg on PATH, then to webm.
 */
function findFfmpeg() {
  // Two resolution roots, because ffmpeg-static can legitimately come from either side:
  // this package's own optionalDependencies (normal install), or the consumer's project (they
  // added it themselves, or a workspace hoisted it somewhere we cannot see from here).
  const roots = [import.meta.url, path.join(projectRoot, 'package.json')]

  for (const root of roots) {
    try {
      const require_ = createRequire(root)
      const bin = require_('ffmpeg-static')
      if (bin && fs.existsSync(bin)) return bin

      const installer = path.join(path.dirname(require_.resolve('ffmpeg-static/package.json')), 'install.js')
      if (fs.existsSync(installer)) {
        console.log('   fetching ffmpeg-static binary (first run only)…')
        spawnSync(process.execPath, [installer], { cwd: path.dirname(installer), stdio: 'inherit' })
        if (bin && fs.existsSync(bin)) return bin
      }
    } catch {
      // Not resolvable from this root — try the next.
    }
  }
  return spawnSync('ffmpeg', ['-version'], { stdio: 'ignore' }).status === 0 ? 'ffmpeg' : null
}

function collectVideos(dir) {
  if (!fs.existsSync(dir)) return []
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) return collectVideos(full)
    return entry.name.endsWith('.webm') ? [full] : []
  })
}

// ---------------------------------------------------------------- run

const baseConfigPath = findBaseConfig()
const generatedConfig = writeDerivedConfig(baseConfigPath)
const outputDir = path.join(workDir, 'output')

console.log(`\n▶  achilles-show — headed, slowMo=${SLOW_MO}ms, video=on, workers=1`)
console.log(`   config: derived from ${path.relative(projectRoot, baseConfigPath)}`)
console.log(`   args:   ${args.join(' ') || '(all tests)'}\n`)

fs.rmSync(outputDir, { recursive: true, force: true })

let run
try {
  run = spawnSync('npx', ['playwright', 'test', `--config=${generatedConfig}`, ...args], {
    cwd: projectRoot,
    stdio: 'inherit',
    env: { ...process.env, E2E_SLOWMO: String(SLOW_MO) },
  })
} finally {
  // The generated config lives beside the project's own; never leave it behind.
  fs.rmSync(generatedConfig, { force: true })
}

const videos = collectVideos(outputDir)
if (videos.length === 0) {
  console.log('\n⚠  No recordings produced. Did any test actually run?\n')
  process.exit(run.status ?? 1)
}

fs.mkdirSync(destDir, { recursive: true })
const ffmpeg = findFfmpeg()
const produced = []

for (const src of videos) {
  // Playwright's per-test folder name is a far better label than the video's uuid filename.
  const label =
    path
      .basename(path.dirname(src))
      .replace(/[^a-zA-Z0-9._-]/g, '-')
      .slice(0, 80) || 'recording'

  if (ffmpeg) {
    const out = path.join(destDir, `${label}.mp4`)
    try {
      // yuv420p is what makes it play in QuickTime and preview in chat clients;
      // +faststart lets it stream before it has finished downloading.
      execFileSync(
        ffmpeg,
        ['-y', '-loglevel', 'error', '-i', src, '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '23', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', out],
        { stdio: 'inherit' },
      )
      produced.push(out)
      continue
    } catch {
      console.log(`   (transcode failed for ${label}, keeping webm)`)
    }
  }

  const fallback = path.join(destDir, `${label}.webm`)
  fs.copyFileSync(src, fallback)
  produced.push(fallback)
}

console.log(`\n🎬  ${produced.length} recording(s) in ${path.relative(projectRoot, destDir)}`)
for (const f of produced) console.log(`    ${path.basename(f)}`)

if (!ffmpeg) {
  console.log('\n⚠  mp4 requested but no usable ffmpeg found — kept webm.')
  console.log('   Playwright bundles a decode-only ffmpeg (no mp4 muxer, no h264). Install one:')
  console.log('     npm install --save-dev ffmpeg-static     (no system install needed)')
  console.log('     brew install ffmpeg                      (if you have Homebrew)\n')
}

process.exit(run.status ?? 0)
